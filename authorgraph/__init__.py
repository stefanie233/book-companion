"""AuthorGraph —— 作者层。与 ``bookgraph`` 并列，但**只做一件事**：

    BookGraph 装**世界里**发生过什么；AuthorGraph 装**世界外面**那个人是谁。

分工的依据在 ``docs/graph-vision.md`` §四：正文是对象层（世界内），
序跋是元层（站在世界外谈论世界），**元层不进 nodes/edges**。所以作者
不在图谱里不是漏提，是按设计他不该在那儿。

四个模块，各自很小：

- ``scope``   环境上下文：采集调用**能看见什么**（只有目录 + 序跋）
- ``harvest`` 一次普通 LLM 调用：判位置 + 采语料 + 抽编年（不是子代理）
- ``gate``    剧透门：章号 → 编年（作者层唯一的门，只有一处计算）
- ``card``    消费端纯函数：台账 → 可注入的作者内核
- ``store``   唯一写入口

两条贯穿全层的原则（详见 ``docs/authorgraph/README.md``）：

1. **证据落库，导出量现算。** 语料与编年是资产；锚点、位置过滤、正名
   显示是看法，消费时算。
2. **看不见就是看不见。** 采集调用拿不到正文，所以「把虚构写进作者
   台账」是结构性不可能，不是靠提示词叮嘱。
"""

