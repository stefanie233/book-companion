def chapter_task(chapter_index: int, title: str, text: str, *,
                 read_before: int, total: int,
                 tool_note: str = "") -> str:
    """逐章任务。章号/正文/已读范围都在这里，系统提示保持不动。"""
    head = (
        f"<chapter index=\"{chapter_index}\" title=\"{title}\">\n"
        f"{text}\n"
        f"</chapter>\n\n"
        f"已读：此前 {read_before} 章；本章是第 {read_before + 1} / {total}"
        f" 章（章节索引 {chapter_index}）。"
    )
    if tool_note:
        head += "\n" + tool_note
    return head + "\n\n读这一章，按 system 里的字段输出 JSON。"


def summary_block(entries: list[tuple[int, str]]) -> str:
    """换窗后的摘要块：只放 compact，不重复正文。"""
    lines = [f"第 {idx} 章：{compact}" for idx, compact in entries]
    return (
        "<reading-summary>\n"
        "以下是你此前读过的章节的压缩笔记。原文已不在上下文里；"
        "需要细节时调用 search_book / read_passage 回查。\n\n"
        + "\n".join(lines)
        + "\n</reading-summary>"
    )


